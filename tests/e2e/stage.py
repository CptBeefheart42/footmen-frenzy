#!/usr/bin/env python3
"""Stages the addon folders for one e2e build (the script runner's FF_JASS_ADDONS / FF_JASS_MAP_ADDONS).

    tests/e2e/stage.py <main|solo> <scenario> <out dir> [--bot <battletag>]

<out dir>/jass is league/ with --bot added to the hosting bots' list (FF_IsHostBotName, which FF_IsBotName
includes), so the client gets everything a hosting fleet bot gets (token file names, the kill log, BotVision, Pub mode
without the host's dialog). Offline (-loadfile) WC3 names the client "Local Player"; the e2e
addon renames it to --bot (01-e2e-client.j), a battletag-like name the league keeps as a player.

<out dir>/map is the map's own addons (projects/<map>/addons, imports included) plus
tests/e2e/addons/core and tests/e2e/addons/<scenario>. A scenario that shares its script with others names the
shared folders under tests/e2e/addons in an `include` file, one per line; their *.j files are staged too.

Release builds never go through here, and verify-map rejects any build with FF_E2E_ symbols.
"""
import argparse
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tests.common.paths import REPO  # noqa: E402

BOT_FUNC = "function FF_IsHostBotName takes string name returns boolean\n"
LOCAL_PLAYER = "Local Player"


def add_bot(common_j, bot):
    """Adds a name to the map's hosting-bot list.

    Args:
        common_j: The text of league/00-common.j.
        bot: The battletag to add.

    Returns:
        The text with the name accepted first thing in FF_IsHostBotName.

    Raises:
        ValueError: When FF_IsHostBotName is not defined exactly once.
    """
    if common_j.count(BOT_FUNC) != 1:
        raise ValueError("FF_IsHostBotName is not defined exactly once in 00-common.j")
    check = (f'    if name != null and FF_EndsWith(name, "{bot}") then\n'
             "        return true\n"
             "    endif\n")
    return common_j.replace(BOT_FUNC, BOT_FUNC + check)


def valid_bot(bot):
    """Whether --bot is a battletag (Name#1234) or WC3's offline name."""
    return bot == LOCAL_PLAYER or re.fullmatch(r"[^\s\",#]+#\d+", bot) is not None


def client_name_addon(bot):
    """The generated addon that names the client (an empty name keeps WC3's own)."""
    name = bot if bot != LOCAL_PLAYER else ""
    return ("// generated by tests/e2e/stage.py: the client's name in this e2e build (E2E_BOT; empty = WC3's own)\n"
            "function FF_E2E_ClientName takes nothing returns string\n"
            f'    return "{name}"\n'
            "endfunction\n")


def includes(scen):
    """The shared folders a scenario's `include` file names (none without the file).

    Args:
        scen: The scenario folder.

    Returns:
        The folders, in the file's order.

    Raises:
        SystemExit: When a named folder does not exist.
    """
    inc = scen / "include"
    if not inc.is_file():
        return []
    dirs = [scen.parent / line.strip() for line in inc.read_text().splitlines() if line.strip()]
    for d in dirs:
        if not d.is_dir():
            sys.exit(f"stage: {inc} names no folder {d}")
    return dirs


def stage(map_name, scenario, out, bot=""):
    """Builds the two addon folders.

    Args:
        map_name: `799x` or `solo`.
        scenario: The scenario folder under tests/e2e/addons.
        out: The stage folder (replaced).
        bot: The client's battletag, or empty for a client off the bot list.

    Raises:
        SystemExit: On an unknown scenario or included folder, an invalid --bot, or an addon file name clash.
    """
    out = Path(out)
    scen = REPO / "tests" / "e2e" / "addons" / scenario
    if not scen.is_dir():
        sys.exit(f"stage: no scenario folder {scen}")
    if bot and not valid_bot(bot):
        sys.exit(f"stage: --bot must be a battletag (Name#1234) or \"{LOCAL_PLAYER}\", got {bot!r}")
    shutil.rmtree(out, ignore_errors=True)
    shutil.copytree(REPO / "league", out / "jass")
    if bot:
        common = out / "jass" / "00-common.j"
        try:
            common.write_text(add_bot(common.read_text(), bot))
        except ValueError as e:
            sys.exit(f"stage: {e}")
    shutil.copytree(REPO / "projects" / map_name / "addons", out / "map", ignore=shutil.ignore_patterns("anchors.txt"))
    (out / "map" / "01-e2e-client.j").write_text(client_name_addon(bot))
    for src in (REPO / "tests" / "e2e" / "addons" / "core", *includes(scen), scen):
        for f in sorted(src.glob("*.j")):
            if (out / "map" / f.name).exists():
                sys.exit(f"stage: {f.name} clashes with a map addon file name")
            shutil.copy2(f, out / "map" / f.name)


def main(argv=None):
    """Stages the folders given on the command line.

    Args:
        argv: The command line (default: sys.argv[1:]).
    """
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("map", choices=["799x", "solo"])
    ap.add_argument("scenario")
    ap.add_argument("out")
    ap.add_argument("--bot", default="")
    a = ap.parse_args(argv)
    stage(a.map, a.scenario, a.out, a.bot)
    print(f"stage: {a.map}/{a.scenario} -> {a.out}" + (f" (bot {a.bot})" if a.bot else ""))


if __name__ == "__main__":
    main()
