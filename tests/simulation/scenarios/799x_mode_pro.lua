-- Pro, the host's second button: Single Draft at once like Pub, start gold 100, and the gold pool open from the
-- first second (settings pooling.pro_open_s): -pool and the autopool (with the gold it keeps back).
local M = require("modes")
M.boot()
M.pick("pro")
local gold = T.gold(1)

M.checkStart(gold, 100)
M.checkTaverns("SD")
T.advance(3)
M.checkTradingOpen(true, "5 s in")
M.checkAlliesOnly(true, "5 s in")
M.checkPoolDialog(true, "5 s in")
M.checkAutopool("5 s in")
T.check("5 s in: the autopool keeps back the threshold the player set", function()
    M.keep150(1)
    local left, moved = M.autopool(1, 2, 1000)
    T.eq(left, 150, "gold kept by slot 1")
    T.eq(moved, 850, "gold arrived at slot 2")
end)
T.advance(240)
M.checkTradingOpen(true, "after 240 s")
M.checkAlliesOnly(true, "after 240 s")
M.checkPoolDialog(true, "after 240 s")
T.flush()
M.checkModes({ sel = 3, pub = 1, inhouse = 0, pro = 1 })
