"""Writes data/object_fields.csv: the World Editor's name of every object-data field, for the readable object files.

Reads the metadata tables and the World Editor's strings from a local pre-3.0 Warcraft III install (CASC), the same
install tools/slk/extract_ability_defaults.py reads:

  war3.w3mod:units/{unit,ability,abilitybuff,upgrade,destructable}metadata.slk, doodads/doodadmetadata.slk,
  ui/skinmetadata.slk                                     field id -> displayName (a WESTRING_ key), category
  war3.w3mod:_locales/enus.w3mod:ui/worldedit{,game}strings.txt   WESTRING_ key -> the name shown in the editor

usage: extract_field_names.py --casc ~/wc3-stage --out data/object_fields.csv
"""
from __future__ import annotations

import argparse
import csv
import io
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from extract_ability_defaults import Casc, parse_slk  # noqa: E402

# kind -> (metadata file, a column that must be "1" for the kind, or None)
METADATA = {
    'unit': ('war3.w3mod:units/unitmetadata.slk', 'useUnit'),
    'item': ('war3.w3mod:units/unitmetadata.slk', 'useItem'),
    'ability': ('war3.w3mod:units/abilitymetadata.slk', None),
    'buff': ('war3.w3mod:units/abilitybuffmetadata.slk', None),
    'upgrade': ('war3.w3mod:units/upgrademetadata.slk', None),
    'destructable': ('war3.w3mod:units/destructablemetadata.slk', None),
    'doodad': ('war3.w3mod:doodads/doodadmetadata.slk', None),
    'skin': ('war3.w3mod:ui/skinmetadata.slk', None),
}
STRINGS = ('war3.w3mod:_locales/enus.w3mod:ui/worldeditstrings.txt',
           'war3.w3mod:_locales/enus.w3mod:ui/worldeditgamestrings.txt')


def read_strings(casc: Casc) -> dict[str, str]:
    """The World Editor's WESTRING_ keys and their English text."""
    strings: dict[str, str] = {}
    for path in STRINGS:
        for line in casc.read(path).decode('utf-8', 'replace').splitlines():
            key, sep, value = line.partition('=')
            if sep and key.startswith('WESTRING'):
                strings[key.strip()] = value.strip().strip('"')
    return strings


def display_name(raw: str, strings: dict[str, str]) -> str:
    """Resolves a displayName (a WESTRING_ key, possibly nested) to plain text without colour codes or hotkey marks."""
    text = strings.get(raw, raw)
    for _ in range(3):
        if text in strings:
            text = strings[text]
    text = re.sub(r'\|c[0-9a-fA-F]{8}|\|r', '', text).replace('&', '')
    return text.strip()


def main() -> int:
    """Writes the field-name table; returns the exit code."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--casc', default='~/wc3-stage')
    parser.add_argument('--out', required=True)
    args = parser.parse_args()
    casc = Casc(os.path.expanduser(args.casc))
    strings = read_strings(casc)
    rows = []
    for kind, (path, use) in METADATA.items():
        _, metas = parse_slk(casc.read(path))
        for meta in metas.values():
            if use and str(meta.get(use, '')).strip() != '1':
                continue
            field = str(meta.get('ID', '')).strip()
            if len(field) != 4:
                continue
            rows.append((kind, field, display_name(str(meta.get('displayName', '')).strip(), strings),
                         str(meta.get('category', '')).strip()))
    rows.sort()
    buffer = io.StringIO()
    buffer.write(f'# Object-data field names as the World Editor shows them, from {os.path.basename(args.casc)} build '
                 f'{casc.build}; generated by tools/slk/extract_field_names.py.\n')
    writer = csv.writer(buffer, lineterminator='\n')
    writer.writerow(['Kind', 'Field', 'Name', 'Category'])
    writer.writerows(rows)
    Path(args.out).write_text(buffer.getvalue(), encoding='utf-8', newline='\n')
    print(f'{len(rows)} fields -> {args.out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
